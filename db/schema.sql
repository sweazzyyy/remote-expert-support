-- =====================================================================
-- Физическая модель данных: система удалённой экспертной поддержки (КТ4)
-- СУБД: PostgreSQL 16+ (проверено на 18.6)
-- Скрипт создаёт схему на пустой базе; повторный запуск пересоздаёт её
-- (все таблицы удаляются вместе с данными).
--   psql -U res_app -d remote_expert -f db/schema.sql
-- =====================================================================

DROP TABLE IF EXISTS annotation, protocol, webrtc_session, expert_assignment,
    incident_skill, incident, priority, equipment, user_skill, skill, app_user CASCADE;

-- ---------------------------------------------------------------------
-- USER. Имя таблицы app_user: слово USER зарезервировано в PostgreSQL.
-- ---------------------------------------------------------------------
CREATE TABLE app_user (
    user_id    bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name  varchar(100) NOT NULL CHECK (btrim(full_name) <> ''),
    email      varchar(100) NOT NULL UNIQUE,
    role       varchar(20)  NOT NULL
               CHECK (role IN ('engineer', 'expert', 'dispatcher', 'admin')),
    rating     numeric(3,2) CHECK (rating BETWEEN 0 AND 5),
    is_active  boolean      NOT NULL DEFAULT true,
    -- рейтинг есть только у эксперта и у эксперта обязателен
    CONSTRAINT app_user_rating_only_expert
        CHECK ((role = 'expert') = (rating IS NOT NULL))
);

-- ---------------------------------------------------------------------
-- SKILL — справочник навыков
-- ---------------------------------------------------------------------
CREATE TABLE skill (
    skill_id  bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      varchar(60) NOT NULL UNIQUE CHECK (btrim(name) <> '')
);

-- ---------------------------------------------------------------------
-- USER_SKILL — навыки эксперта (M:N USER–SKILL)
-- ---------------------------------------------------------------------
CREATE TABLE user_skill (
    user_id   bigint NOT NULL REFERENCES app_user (user_id) ON DELETE CASCADE,
    skill_id  bigint NOT NULL REFERENCES skill (skill_id)   ON DELETE RESTRICT,
    PRIMARY KEY (user_id, skill_id)
);
-- обратный поиск «кто владеет навыком» (PK начинается с user_id)
CREATE INDEX user_skill_skill_idx ON user_skill (skill_id);

-- ---------------------------------------------------------------------
-- EQUIPMENT
-- ---------------------------------------------------------------------
CREATE TABLE equipment (
    equipment_id  bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial_num    varchar(40)  NOT NULL UNIQUE,
    model         varchar(100) NOT NULL,
    location      varchar(100) NOT NULL
);

-- ---------------------------------------------------------------------
-- PRIORITY — справочник уровней приоритета и их весов
-- ---------------------------------------------------------------------
CREATE TABLE priority (
    priority_level  varchar(10) PRIMARY KEY
                    CHECK (priority_level IN ('critical', 'high', 'medium', 'low')),
    weight          smallint    NOT NULL UNIQUE CHECK (weight > 0)
);

-- ---------------------------------------------------------------------
-- INCIDENT
-- ---------------------------------------------------------------------
CREATE TABLE incident (
    incident_id     bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id    bigint       NOT NULL REFERENCES equipment (equipment_id) ON DELETE RESTRICT,
    engineer_id     bigint       NOT NULL REFERENCES app_user (user_id)       ON DELETE RESTRICT,
    priority_level  varchar(10)  NOT NULL REFERENCES priority (priority_level) ON DELETE RESTRICT,
    title           varchar(200) NOT NULL CHECK (btrim(title) <> ''),
    description     text         NOT NULL,
    category        varchar(60)  NOT NULL,
    status          varchar(20)  NOT NULL DEFAULT 'created'
                    CHECK (status IN ('created', 'assigned', 'resolved')),
    created_at      timestamp    NOT NULL DEFAULT now()
);
-- очередь (Алгоритм 2) выбирает инциденты в статусе created
CREATE INDEX incident_status_idx    ON incident (status);
CREATE INDEX incident_equipment_idx ON incident (equipment_id);
CREATE INDEX incident_engineer_idx  ON incident (engineer_id);

-- ---------------------------------------------------------------------
-- INCIDENT_SKILL — навыки, требуемые для инцидента (M:N INCIDENT–SKILL)
-- ---------------------------------------------------------------------
CREATE TABLE incident_skill (
    incident_id  bigint NOT NULL REFERENCES incident (incident_id) ON DELETE CASCADE,
    skill_id     bigint NOT NULL REFERENCES skill (skill_id)       ON DELETE RESTRICT,
    PRIMARY KEY (incident_id, skill_id)
);
CREATE INDEX incident_skill_skill_idx ON incident_skill (skill_id);

-- ---------------------------------------------------------------------
-- EXPERT_ASSIGNMENT. UNIQUE (incident_id): эксперта назначают только
-- на инцидент в статусе created, поэтому назначение у инцидента одно.
-- ---------------------------------------------------------------------
CREATE TABLE expert_assignment (
    assignment_id  bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id    bigint       NOT NULL UNIQUE REFERENCES incident (incident_id) ON DELETE RESTRICT,
    expert_id      bigint       NOT NULL REFERENCES app_user (user_id)          ON DELETE RESTRICT,
    score          numeric(7,2) NOT NULL CHECK (score >= 100),
    assigned_at    timestamp    NOT NULL DEFAULT now()
);
CREATE INDEX expert_assignment_expert_idx ON expert_assignment (expert_id);

-- ---------------------------------------------------------------------
-- SESSION (WebRTC). UNIQUE (assignment_id): не более одного сеанса
-- на назначение (кратность 0..1).
-- ---------------------------------------------------------------------
CREATE TABLE webrtc_session (
    session_id      bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id   bigint      NOT NULL UNIQUE
                    REFERENCES expert_assignment (assignment_id) ON DELETE RESTRICT,
    room_id         varchar(64) NOT NULL UNIQUE,
    quality         varchar(30) NOT NULL,
    established_at  timestamp   NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- ANNOTATION — AR-метка; принадлежит сеансу (композиция → CASCADE)
-- ---------------------------------------------------------------------
CREATE TABLE annotation (
    annotation_id  bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id     bigint       NOT NULL REFERENCES webrtc_session (session_id) ON DELETE CASCADE,
    tool_type      varchar(10)  NOT NULL CHECK (tool_type IN ('arrow', 'rect', 'line')),
    x1             numeric(5,4) NOT NULL CHECK (x1 BETWEEN 0 AND 1),
    y1             numeric(5,4) NOT NULL CHECK (y1 BETWEEN 0 AND 1),
    x2             numeric(5,4) NOT NULL CHECK (x2 BETWEEN 0 AND 1),
    y2             numeric(5,4) NOT NULL CHECK (y2 BETWEEN 0 AND 1),
    color          char(7)      NOT NULL CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
    created_at     timestamp    NOT NULL DEFAULT now()
);
CREATE INDEX annotation_session_idx ON annotation (session_id);

-- ---------------------------------------------------------------------
-- PROTOCOL — протокол заключения; один на сеанс
-- ---------------------------------------------------------------------
CREATE TABLE protocol (
    protocol_id   bigint    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id    bigint    NOT NULL UNIQUE REFERENCES webrtc_session (session_id) ON DELETE RESTRICT,
    expert_notes  text      NOT NULL CHECK (btrim(expert_notes) <> ''),
    closed_at     timestamp NOT NULL DEFAULT now()
);
